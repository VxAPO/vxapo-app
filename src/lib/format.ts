/** 界面数值格式化：带符号的 dB 那类坑集中在这里。 */

/**
 * 增益/峰值的 dB 数值（**不带单位**，单位由调用方拼）。
 *
 * 关键：**先四舍五入到 1 位小数，再决定符号**。
 * 写成 `(db >= 0 ? "+" : "") + db.toFixed(1)` 会在 |db| < 0.05 时留下负号——
 * `(-0.04).toFixed(1)` 是 `"-0.0"`，而归一化恰好会把峰值压到 0 附近，界面于是显示
 * 「-0.0 dB」（踩过）。
 *
 * 先 `Number(v.toFixed(1))` 把 `-0` 归一成 `0`（`(-0.04).toFixed(1)` → `"-0.0"` → `-0`），
 * 再 `toFixed(1)` 输出就是 `"0.0"`；同时也保证 `0.04` 不会被写成 `"+0.0"`。
 */
export function fmtDb1(db: number): string {
  const v = Number(db.toFixed(1));
  return `${v > 0 ? "+" : ""}${v.toFixed(1)}`;
}
